package frontdoor

import "text/template"

// GRPCRoute is one gRPC method the Agents listener forwards to the Gateway.
type GRPCRoute struct {
	// Path is "/<package>.<Service>/<Method>".
	Path string
	// NeedsClientCert is false only for Enroll, which is how a host gets
	// its certificate.
	NeedsClientCert bool
}

// HTTPRoute is one HTTP path the Agents listener forwards to the Gateway.
type HTTPRoute struct {
	Path            string
	NeedsClientCert bool
}

// grpcRoutes are the gRPC methods Agents and Gateways call. A test checks
// them against the Protobuf definitions in proto/.
var grpcRoutes = []GRPCRoute{
	{Path: "/observex.agent.v1.EnrollmentService/Enroll", NeedsClientCert: false},
	{Path: "/observex.agent.v1.EnrollmentService/GetConfig", NeedsClientCert: true},
	{Path: "/observex.ingest.v1.IngestService/Send", NeedsClientCert: true},
	{Path: "/opentelemetry.proto.collector.metrics.v1.MetricsService/Export", NeedsClientCert: true},
	{Path: "/opentelemetry.proto.collector.logs.v1.LogsService/Export", NeedsClientCert: true},
	{Path: "/opentelemetry.proto.collector.trace.v1.TraceService/Export", NeedsClientCert: true},
}

// httpRoutes are the OTLP/HTTP paths.
var httpRoutes = []HTTPRoute{
	{Path: "/v1/metrics", NeedsClientCert: true},
	{Path: "/v1/logs", NeedsClientCert: true},
	{Path: "/v1/traces", NeedsClientCert: true},
}

// GRPCRoutes returns the gRPC routes of the Agents listener.
func GRPCRoutes() []GRPCRoute { return append([]GRPCRoute(nil), grpcRoutes...) }

// HTTPRoutes returns the HTTP routes of the Agents listener.
func HTTPRoutes() []HTTPRoute { return append([]HTTPRoute(nil), httpRoutes...) }

